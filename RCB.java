class RCB {
    int teamId;
    String captain;
    String coach;
    
public void setTeamId(int teamId){
this.teamId = teamId; 
}
public void setCaptain(String captain){
this.captain = captain; 
}
public void setCoach(String coach) {
this.coach = coach; 
}
  
  
public int getTeamId() {
return teamId;
}
public String getCaptain() {
return captain; 
}
public String getCoach() {
return coach; 
}
}