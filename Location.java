class Location {
    int id;
    String street;
    String area;
    String city;
    int pincode;
    
    public void setId(int id) { 
	this.id = id; 
	}
	
    public void setStreet(String street) {
	this.street = street;
	}
	
    public void setArea(String area) {
	this.area = area; 
	}
	
    public void setCity(String city) { 
	this.city = city; 
	}
    public void setPincode(int pincode) {
	this.pincode = pincode; 
	}
}
