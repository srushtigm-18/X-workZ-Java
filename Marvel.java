class Marvel {
    private int heroId;
    private String heroName;
    private String powerClass;
    private String primaryPower;
    private String team;
    private String firstAppearance;
    private String releaseDate;
    private String status;

    public void setHeroId(int heroId) {
        this.heroId = heroId;
    }
    public int getHeroId() {
        return this.heroId;
    }

    public void setHeroName(String heroName) {
        this.heroName = heroName;
    }
    public String getHeroName() {
        return this.heroName;
    }

    public void setPowerClass(String powerClass) {
        this.powerClass = powerClass;
    }
    public String getPowerClass() {
        return this.powerClass;
    }

    public void setPrimaryPower(String primaryPower) {
        this.primaryPower = primaryPower;
    }
    public String getPrimaryPower() {
        return this.primaryPower;
    }

    public void setTeam(String team) {
        this.team = team;
    }
    public String getTeam() {
        return this.team;
    }

    public void setFirstAppearance(String firstAppearance) {
        this.firstAppearance = firstAppearance;
    }
    public String getFirstAppearance() {
        return this.firstAppearance;
    }

    public void setReleaseDate(String releaseDate) {
        this.releaseDate = releaseDate;
    }
    public String getReleaseDate() {
        return this.releaseDate;
    }

    public void setStatus(String status) {
        this.status = status;
    }
    public String getStatus() {
        return this.status;
    }
}