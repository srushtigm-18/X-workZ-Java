class Capacitor {

int id;
String brandName;
String colour;
int speed;
    
public void setId(int id) { 
this.id = id; 
}

public void setBrandName(String brandName) {
this.brandName = brandName;
}

public void setColour(String colour) {
this.colour = colour;
}

public void setSpeed(int speed) {

this.speed = speed;
}
}
